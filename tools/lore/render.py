#!/usr/bin/env python3
"""Render lore/ JSON into Markdown views (never edit those by hand).

  python3 tools/lore/render.py [--root DIR]

Writes docs/creatures/<id>.md, docs/creatures/README.md (grouped by world), docs/lore/worlds/<id>.md, docs/lore/REFERENCES.md.
"""
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lorelib import ROOT, load, creature_files, flora_files

HEADER = "<!-- generated by tools/lore/render.py, do not edit -->\n"
BADGE = {"draft": "DRAFT", "reviewed": "REVIEWED", "canon": "CANON"}
MARK = {"verified": "[verified]", "unverified": "[unverified]", "rejected": "[rejected]"}


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def author_year(r):
    au = r.get("author") or []
    fam = [a.get("family") or a.get("literal") or "?" for a in au]
    if not fam: who = "Anon."
    elif len(fam) == 1: who = fam[0]
    elif len(fam) == 2: who = f"{fam[0]} & {fam[1]}"
    else: who = f"{fam[0]} et al."
    try: yr = r["issued"]["date-parts"][0][0]
    except (KeyError, IndexError, TypeError): yr = "n.d."
    return f"{who} {yr}"


def cite(rid, refs):
    r = refs.get(rid)
    if not r: return f"{rid} [missing]"
    return f"{author_year(r)} {MARK.get(r.get('x-status'), '[?]')}"


def full_ref(r):
    s = f"{author_year(r)}. {r['title']}."
    if r.get("container-title"): s += f" *{r['container-title']}*."
    for k in ("DOI", "ISBN"):
        if r.get(k): s += f" {k}: {r[k]}."
    return s


def lang(d, k="en"):
    return d.get(k) or d.get("en", "")


def render_creature(c, world, refs):
    facts = {f["id"]: f for f in (world or {"facts": []})["facts"]}
    o = [HEADER, f"# {c['name']['en']}" + (f" ({c['name']['es']})" if c["name"].get("es", c["name"]["en"]) != c["name"]["en"] else ""), ""]
    o.append(f"**Status: {BADGE[c['status']]}** · world: [{c['world']}](../lore/worlds/{c['world']}.md) · kind: {c.get('kind', 'native')} · stage: {c['stage']} · id: `{c['id']}`" + (f" · aliases: {', '.join(c['aliases'])}" if c.get("aliases") else ""))
    if c.get("lore_ref"): o.append(f"\nThird-party lore: `{c['lore_ref']['file']}` / `{c['lore_ref']['id']}`")
    o += ["", "## Niche", ""]
    n = c["niche"]
    o += [f"- **Habitat:** {n['habitat']}", f"- **Diet:** {n['diet']}", f"- **Active:** {n['active']}",
          f"- **Predators:** {', '.join(n['predators']) or 'none'}"]
    if n.get("prey"): o.append(f"- **Prey:** {', '.join(n['prey'])}")
    o += ["", "## Body", "", c["body"]]
    if c.get("temperament"): o += ["", f"**Temperament:** {c['temperament']}"]
    o += ["", "## Causal chains", "", "| Chain | Trait | Links | Roots (planet facts) | Skill | Role | Effect | Weakness |", "|---|---|---|---|---|---|---|---|"]
    for ch in c["chains"]:
        roots = "; ".join(f"**{r}** {facts[r]['claim']}" if r in facts else f"**{r}** (missing)" for r in ch["roots"])
        sk = ch["skill"]
        o.append("| " + " | ".join(cell(x) for x in [ch["id"], ch["trait"], " ← ".join(ch["links"]), roots, sk["name"]["en"] + f" (`{sk['id']}`)", sk["role"], sk["effect"], ch["weakness"]]) + " |")
    for ch in c["chains"]:
        pl = ch["plausibility"]
        o += ["", f"### {ch['id']}: {ch['trait']}", "",
              "Trait ← " + " ← ".join(ch["links"]) + " ← " + ", ".join(ch["roots"]), "",
              f"- **Skill:** {ch['skill']['name']['en']} ({ch['skill']['role']}): {ch['skill']['effect']}"
              + (" " + ", ".join(f"{k}={v:g}" for k, v in sorted(ch["skill"].get("numbers", {}).items())) if ch["skill"].get("numbers") else ""),
              f"- **Weakness:** {ch['weakness']}", "- **Observe:**"]
        o += [f"  {i}. {s}" for i, s in enumerate(ch["observe"], 1)]
        o += [f"- **Journal:** {lang(ch['journal'])}" + (f" / {ch['journal']['es']}" if ch["journal"].get("es") else ""),
              f"- **Plausibility:** {pl['verdict']} (judge {pl['judge']}, {pl['date']})"]
        if pl.get("summary"): o.append(f"  - {pl['summary']}")
        if pl.get("scores"): o.append("  - scores: " + ", ".join(f"{k} {v}" for k, v in sorted(pl["scores"].items())))
        for a in pl.get("analogues", []):
            cs = "; ".join(cite(r, refs) for r in a.get("refs", []))
            o.append(f"  - Analogue: {a['organism']}: {a['mechanism']}" + (f" ({cs})" if cs else ""))
        for f in pl.get("fixes", []): o.append(f"  - Fix: {f}")
        if ch.get("provenance"): o.append("- **Chain provenance:** " + prov(ch["provenance"]))
    if c.get("relations"):
        o += ["", "## Relations", "", "| With | Kind | Via | Note |", "|---|---|---|---|"]
        o += ["| " + " | ".join(cell(x) for x in [r["with"], r["kind"], r.get("via", ""), r["note"]]) + " |" for r in c["relations"]]
    if c.get("journal"):
        o += ["", "## Journal", ""] + [f"- EN: {j['en']}" + (f"\n  ES: {j['es']}" if j.get("es") else "") for j in c["journal"]]
    for key, title in (("secrets", "Secrets"), ("moments", "Moments")):
        if c.get(key): o += ["", f"## {title}", ""] + [f"- {x}" for x in c[key]]
    if c.get("provenance"): o += ["", "## Provenance", "", prov(c["provenance"])]
    o += ["", "## Changelog", ""] + [f"- {e['date']} {e['who']}: {e['what']}" for e in c["changelog"]]
    return "\n".join(o) + "\n"


def render_plant(c, world, refs):
    facts = {f["id"]: f for f in (world or {"facts": []})["facts"]}
    g = c["generator"]
    o = [HEADER, f"# {c['name']['en']}" + (f" ({c['name']['es']})" if c["name"].get("es", c["name"]["en"]) != c["name"]["en"] else ""), "",
         f"**Status: {BADGE[c['status']]}** · world: [{c['world']}](../worlds/{c['world']}.md) · form: {c['growth_form']} · id: `{c['id']}`", "",
         c["summary"], "", f"**Habitats:** {', '.join(c['habitats'])}", "", "## Causal chains", ""]
    for ch in c["chains"]:
        pl = ch["plausibility"]
        roots = "; ".join(f"**{r}** {facts[r]['claim']}" if r in facts else f"**{r}** (missing)" for r in ch["roots"])
        o += [f"### {ch['id']}: {ch['trait']}", "", "Trait ← " + " ← ".join(ch["links"]) + " ← " + roots, "", f"- **In play:** {ch['play']}"]
        if ch.get("weakness"): o.append(f"- **Weakness:** {ch['weakness']}")
        o += ["- **Observe:**"] + [f"  {i}. {s}" for i, s in enumerate(ch["observe"], 1)]
        o.append(f"- **Plausibility:** {pl['verdict']} (judge {pl['judge']}, {pl['date']})")
        if pl.get("summary"): o.append(f"  - {pl['summary']}")
        for a in pl.get("analogues", []):
            cs = "; ".join(cite(r, refs) for r in a.get("refs", []))
            o.append(f"  - Analogue: {a['organism']}: {a['mechanism']}" + (f" ({cs})" if cs else ""))
        for f in pl.get("fixes", []): o.append(f"  - Fix: {f}")
        o.append("")
    o += ["## Gameplay", "", "```json", json.dumps(c["gameplay"], indent=1, ensure_ascii=False), "```", ""]
    if c.get("relations"):
        o += ["## Relations", "", "| With | Kind | Note |", "|---|---|---|"] + ["| " + " | ".join(cell(x) for x in [r["with"], r["kind"], r["note"]]) + " |" for r in c["relations"]] + [""]
    o += ["## Generator parameters", "", "```json", json.dumps(g, indent=1, ensure_ascii=False), "```", ""]
    if c.get("observe"): o += ["## Observe", ""] + [f"- {x}" for x in c["observe"]] + [""]
    if c.get("journal"): o += ["## Journal", ""] + [f"- EN: {j['en']}" + (f"\n  ES: {j['es']}" if j.get("es") else "") for j in c["journal"]] + [""]
    if c.get("secrets"): o += ["## Secrets", ""] + [f"- {x}" for x in c["secrets"]] + [""]
    if c.get("provenance"): o += ["## Provenance", "", prov(c["provenance"]), ""]
    o += ["## Changelog", ""] + [f"- {e['date']} {e['who']}: {e['what']}" for e in c["changelog"]]
    return "\n".join(o) + "\n"


def render_flora_index(plants, worlds):
    o = [HEADER, "# Flora", ""]
    for wid in sorted({c["world"] for c in plants}):
        w = worlds.get(wid)
        o += [f"## {w['name']['en'] if w else wid} (`{wid}`)", "", "| Plant | Form | Height (m) | Habitats | Status | Chains | Verdicts |", "|---|---|---|---|---|---|---|"]
        for c in sorted((c for c in plants if c["world"] == wid), key=lambda c: c["id"]):
            v = {}
            for ch in c["chains"]: v[ch["plausibility"]["verdict"]] = v.get(ch["plausibility"]["verdict"], 0) + 1
            h = c["generator"]["height_m"]
            o.append(f"| [{c['name']['en']}](flora/{c['id']}.md) | {c['growth_form']} | {h['min']:g}-{h['max']:g} | {cell(', '.join(c['habitats']))} | {c['status']} | {len(c['chains'])} | " + ", ".join(f"{n} {k}" for k, n in sorted(v.items())) + " |")
        o.append("")
    return "\n".join(o).rstrip("\n") + "\n"


def prov(p):
    parts = []
    if p.get("council_run"): parts.append(f"council run `{p['council_run']}`")
    if p.get("by"): parts.append("by " + ", ".join(p["by"]))
    if p.get("edited_by"): parts.append(f"edited by {p['edited_by']}")
    return "; ".join(parts) or "none recorded"


def render_index(cres, worlds):
    o = [HEADER, "# Creatures", ""]
    for wid in sorted({c["world"] for c in cres}):
        w = worlds.get(wid)
        o += [f"## {w['name']['en'] if w else wid} (`{wid}`)", "", "| Creature | Kind | Status | Chains | Verdicts |", "|---|---|---|---|---|"]
        for c in sorted((c for c in cres if c["world"] == wid), key=lambda c: c["id"]):
            v = {}
            for ch in c["chains"]: v[ch["plausibility"]["verdict"]] = v.get(ch["plausibility"]["verdict"], 0) + 1
            o.append(f"| [{c['name']['en']}]({c['id']}.md) | {c.get('kind', 'native')} | {c['status']} | {len(c['chains'])} | " + ", ".join(f"{n} {k}" for k, n in sorted(v.items())) + " |")
        o.append("")
    return "\n".join(o).rstrip("\n") + "\n"


def render_world(w, refs):
    sy = w["system"]
    o = [HEADER, f"# {w['name']['en']}", "", f"Status: **{BADGE[w['status']]}** · kind: {w['kind']} · id: `{w['id']}`", "",
         f"- **Star:** {sy['star']}", f"- **Position:** {sy['position']}",
         "- **Distance from Sol:** " + ("n/a" if sy["distance_ly_from_sol"] is None else f"{sy['distance_ly_from_sol']:g} ly")]
    if w.get("lore_source"): o.append(f"- **Lore source:** `{w['lore_source']}`")
    o += ["", "| Fact | Group | Claim | Value | Justification | References | Status |", "|---|---|---|---|---|---|---|"]
    for f in sorted(w["facts"], key=lambda f: int(f["id"][1:])):
        val = f"{f['value']} {f.get('unit', '')}".strip() if "value" in f else ""
        o.append("| " + " | ".join(cell(x) for x in [f["id"], f["group"], f["claim"], val, f["justification"],
                 "; ".join(cite(r, refs) for r in f.get("refs", [])), f["status"]]) + " |")
    cons = [f for f in w["facts"] if f.get("consequences")]
    if cons:
        o += ["", "## Consequences", ""]
        for f in cons: o += [f"- **{f['id']}**: " + "; ".join(f["consequences"])]
    o += ["", "## Changelog", ""] + [f"- {e.get('date', '')} {e.get('who', '')}: {e.get('what', '')}" for e in w["changelog"]]
    return "\n".join(o) + "\n"


def render_refs(reflist, usage):
    o = [HEADER, "# References", ""]
    for st in ("verified", "unverified", "rejected"):
        rs = sorted((r for r in reflist if r["x-status"] == st), key=lambda r: (author_year(r), r["id"]))
        o += [f"## {st.capitalize()} ({len(rs)})", ""]
        for r in rs:
            line = f"- `{r['id']}`: {full_ref(r)}"
            if r.get("x-checked"): line += f" Checked {r['x-checked']}."
            if r.get("x-note"): line += f" Note: {r['x-note'].rstrip('.')}."
            if usage.get(r["id"]): line += f" Cited by: {', '.join(sorted(usage[r['id']]))}."
            o.append(line)
        if not rs: o.append("None.")
        o.append("")
    return "\n".join(o).rstrip("\n") + "\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f: f.write(text)


def render_all(root):
    wdir = os.path.join(root, "lore", "worlds")
    worlds = {}
    for n in sorted(os.listdir(wdir)):
        if n.endswith(".json"):
            w = load(os.path.join(wdir, n)); worlds[w["id"]] = w
    reflist = load(os.path.join(root, "lore", "references.json"))
    refs = {r["id"]: r for r in reflist}
    cres = [load(p) for p in creature_files(root)]
    out, usage = {}, {}
    for c in cres:
        out[f"docs/creatures/{c['id']}.md"] = render_creature(c, worlds.get(c["world"]), refs)
        for ch in c["chains"]:
            for a in ch["plausibility"].get("analogues", []):
                for r in a.get("refs", []): usage.setdefault(r, set()).add(c["id"])
    for wid, w in worlds.items():
        out[f"docs/lore/worlds/{wid}.md"] = render_world(w, refs)
        for f in w["facts"]:
            for r in f.get("refs", []): usage.setdefault(r, set()).add(f"{wid} {f['id']}")
    plants = [load(p) for p in flora_files(root)]
    for c in plants:
        out[f"docs/lore/flora/{c['id']}.md"] = render_plant(c, worlds.get(c["world"]), refs)
        for ch in c["chains"]:
            for a in ch["plausibility"].get("analogues", []):
                for r in a.get("refs", []): usage.setdefault(r, set()).add(f"flora {c['id']}")
    if plants: out["docs/lore/FLORA.md"] = render_flora_index(plants, worlds)
    out["docs/creatures/README.md"] = render_index(cres, worlds)
    out["docs/lore/REFERENCES.md"] = render_refs(reflist, usage)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=ROOT)
    a = ap.parse_args()
    out = render_all(a.root)
    for rel, text in sorted(out.items()): write(os.path.join(a.root, rel), text)
    print(f"lore render: {len(out)} file(s)")


if __name__ == "__main__":
    main()
