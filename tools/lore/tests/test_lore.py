import copy, json, os, shutil, sys, tempfile, unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import validate, render, import_got  # noqa: E402
from lorelib import ROOT, load, dump  # noqa: E402

FIX = os.path.join(HERE, "fixtures", "got")


def make_root():
    d = tempfile.mkdtemp(prefix="lore_test_")
    shutil.copytree(os.path.join(ROOT, "lore"), os.path.join(d, "lore"))
    return d


class Base(unittest.TestCase):
    def setUp(self):
        self.root = make_root()
        self.addCleanup(shutil.rmtree, self.root, True)
        self.cp = os.path.join(self.root, "lore", "creatures", "ecolumbre.json")
        self.wp = os.path.join(self.root, "lore", "worlds", "primigenia.json")
        self.rp = os.path.join(self.root, "lore", "references.json")

    def edit(self, path, fn):
        d = load(path); fn(d); dump(d, path)

    def errors(self):
        return validate.validate_all(self.root)

    def assertError(self, text):
        errs, _ = self.errors()
        self.assertTrue(any(text in e for e in errs), f"{text!r} not in {errs}")


class ValidateTests(Base):
    def test_repo_is_clean(self):
        errs, _ = self.errors()
        self.assertEqual(errs, [])

    def test_schema_error(self):
        self.edit(self.cp, lambda c: c.pop("body"))
        self.assertError("body")

    def test_unknown_root(self):
        self.edit(self.cp, lambda c: c["chains"][0]["roots"].append("F77"))
        self.assertError("F77")

    def test_retired_root(self):
        def f(w): w["facts"][3]["status"] = "retired"
        self.edit(self.wp, f)
        self.assertError("retired")

    def test_unknown_ref(self):
        self.edit(self.cp, lambda c: c["chains"][0]["plausibility"]["analogues"][0]["refs"].append("nope_1999_x"))
        self.assertError("nope_1999_x")

    def test_rejected_ref_cited(self):
        def f(r): r[0]["x-status"] = "rejected"
        self.edit(self.rp, f)
        self.assertError("rejected and must not be cited")

    def test_chain_prefix_and_duplicate(self):
        def f(c):
            c["chains"][0]["id"] = "other.c1"
            c["chains"][2]["id"] = c["chains"][1]["id"]
        self.edit(self.cp, f)
        self.assertError("not prefixed")
        self.assertError("duplicate chain id")

    def test_duplicate_skill_across_creatures(self):
        other = load(self.cp); other["id"] = "twin"
        for i, ch in enumerate(other["chains"]): ch["id"] = f"twin.c{i + 1}"
        dump(other, os.path.join(self.root, "lore", "creatures", "twin.json"))
        self.assertError("duplicate skill id")

    def test_relation_warning_when_draft_error_when_canon(self):
        errs, warns = self.errors()
        self.assertTrue(any("nocturnal creature" in w for w in warns))
        self.edit(self.cp, lambda c: c.update(status="canon"))
        self.assertError("not a known creature id or alias")

    def test_alias_resolves(self):
        self.edit(self.cp, lambda c: c.update(aliases=["nocturnal creature", "rondo"]))
        _, warns = self.errors()
        self.assertEqual(warns, [])

    def test_unknown_world(self):
        self.edit(self.cp, lambda c: c.update(world="atlantis"))
        self.assertError("atlantis")

    def test_real_world_facts_need_refs(self):
        def f(w): w["kind"] = "real"
        self.edit(self.wp, f)
        self.assertError("real world must cite references")


class RenderTests(Base):
    def test_deterministic_and_marked(self):
        a, b = render.render_all(self.root), render.render_all(self.root)
        self.assertEqual(a, b)
        self.assertIn("docs/creatures/ecolumbre.md", a)
        self.assertIn("docs/lore/worlds/primigenia.md", a)
        for text in a.values(): self.assertTrue(text.startswith("<!-- generated by tools/lore/render.py, do not edit -->"))
        self.assertIn("[verified]", a["docs/creatures/ecolumbre.md"])
        self.assertIn("Primigenia", a["docs/creatures/README.md"])

    def test_repo_docs_up_to_date(self):
        for rel, text in render.render_all(ROOT).items():
            p = os.path.join(ROOT, rel)
            self.assertTrue(os.path.exists(p), rel)
            self.assertEqual(open(p, encoding="utf-8").read(), text, f"{rel} is stale: run make lore-check")


class ImportTests(Base):
    def run_import(self, world="primigenia"):
        graph = load(os.path.join(FIX, "graph.json"))
        return import_got.build(graph, FIX, "got-test", "2026-11-18", world)

    def test_build(self):
        docs = self.run_import()
        self.assertEqual(sorted(docs), ["nocturnal_creature", "rondo"])
        r = docs["rondo"]
        self.assertEqual((r["status"], r["world"]), ("draft", "primigenia"))
        self.assertEqual([c["id"] for c in r["chains"]], ["rondo.c1", "rondo.c2"])
        self.assertEqual(r["chains"][0]["skill"]["id"], "rondo.long_hum")
        self.assertEqual(r["chains"][0]["plausibility"]["verdict"], "plausible")
        self.assertEqual(r["chains"][0]["plausibility"]["scores"], {"astrobio": 8, "physicist": 9})
        self.assertEqual(r["chains"][1]["plausibility"]["verdict"], "fixable")
        self.assertEqual(r["chains"][1]["skill"]["role"], "Passive")  # unknown role falls back
        self.assertEqual(r["chains"][1]["roots"], ["F3", "F99"])  # kept; the validator flags unknown ids
        self.assertEqual(docs["nocturnal_creature"]["chains"][0]["plausibility"]["verdict"], "unreviewed")
        kinds = {(x["with"], x["kind"]) for x in r["relations"]}
        self.assertEqual(kinds, {("nocturnal_creature", "predation"), ("Ecolumbre", "counter")})

    def test_schema_valid(self):
        import jsonschema
        schema = load(os.path.join(ROOT, "lore", "schema", "creature.schema.json"))
        for d in self.run_import().values():
            jsonschema.Draft202012Validator(schema).validate(d)

    def test_merge_and_never_overwrite(self):
        docs = self.run_import()
        d = docs["rondo"]
        merged, (added, upd, rel) = import_got.merge(d, self.run_import()["rondo"], "2026-11-19", "got-2")
        self.assertEqual((added, rel), (0, 0))
        self.assertEqual(len(merged["changelog"]), 2)
        extra = copy.deepcopy(docs["rondo"]); extra["chains"][1]["trait"] = "a new trait"
        merged, (added, _, _) = import_got.merge(d, extra, "2026-11-19", "got-2")
        self.assertEqual((added, [c["id"] for c in merged["chains"]]), (1, ["rondo.c1", "rondo.c2", "rondo.c3"]))
        # the CLI refuses reviewed files
        dump(dict(d, status="reviewed"), os.path.join(self.root, "lore", "creatures", "rondo.json"))
        sys.argv = ["import_got", os.path.join(FIX, "graph.json"), "--world", "primigenia", "--root", self.root, "--date", "2026-11-19"]
        import_got.main()
        self.assertEqual(load(os.path.join(self.root, "lore", "creatures", "rondo.json"))["status"], "reviewed")
        self.assertTrue(os.path.exists(os.path.join(self.root, "lore", "creatures", "nocturnal_creature.json")))


if __name__ == "__main__":
    unittest.main()


class ImportMapTests(Base):
    def test_map_ids_aliases_and_references(self):
        g = json.load(open(os.path.join(FIX, "graph.json")))
        name = next(iter(g["chains"]))
        g["chains"][name][0]["references"] = [{"author": "Smith, J.", "year": 2001, "title": "Sound in dense air", "venue": "Journal of Tests"}]
        refs = {}
        docs = import_got.build(g, FIX, "run", "2026-01-01", "primigenia", "native",
                                {name: {"id": "renamed", "name": {"en": "Renamed"}, "aliases": ["old name"], "lore_ref": {"file": "x.json", "id": "y"}}}, refs)
        d = docs["renamed"]
        self.assertEqual(d["name"], {"en": "Renamed"}); self.assertEqual(d["aliases"], ["old name"]); self.assertEqual(d["lore_ref"]["id"], "y")
        self.assertIn("smith_2001_sound", refs)
        self.assertEqual(refs["smith_2001_sound"]["x-status"], "unverified")
        self.assertEqual(d["chains"][0]["plausibility"]["analogues"][-1]["refs"], ["smith_2001_sound"])
