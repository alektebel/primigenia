// F4: the shipped island. data/islands/star_massif.island.json (the source of truth) -> its three derived copies:
//   godot/game/data/islands/star_massif.isl      the ISL1 blob, for the extension and the dev tools
//   core/src/islands/star_massif.inc             the same bytes as a C array, compiled into libcpore (cp_island_star_massif)
//   web/gaitlab/island/star_massif.island.json   the editor's copy of the source (byte for byte)
//   node tools/island/freeze.mjs            write them
//   node tools/island/freeze.mjs --check    write nothing; exit 1 if any copy is missing or stale
// Reproducible: the blob is packed twice and the two must be the same bytes; nothing else (no date, no path) goes into any output.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { packIsland, crc32 } from './pack.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = 'data/islands/star_massif.island.json';
const OUT = { isl: 'godot/game/data/islands/star_massif.isl', inc: 'core/src/islands/star_massif.inc', web: 'web/gaitlab/island/star_massif.island.json' };
const check = process.argv.includes('--check');

const text = fs.readFileSync(path.join(root, SRC), 'utf8');
const a = packIsland(JSON.parse(text)), b = packIsland(JSON.parse(text));
if (!Buffer.from(a).equals(Buffer.from(b))) { console.error('island-pack: two packs of the same JSON differ'); process.exit(1); }

function inc(blob) {
  const rows = [];
  for (let i = 0; i < blob.length; i += 16) rows.push('  ' + Array.from(blob.subarray(i, i + 16), (v) => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ',');
  return `/* GENERATED by tools/island/freeze.mjs (make island-pack) from ${SRC}. Do not edit.\n` +
    ` * The shipped island (Star massif, frozen by A101) as an ISL1 blob: ${blob.length} bytes, crc32 ${crc32(blob, 12, 16).toString(16).padStart(8, '0')}. */\n` +
    `static const uint8_t CP_ISLAND_STAR_MASSIF_BLOB[${blob.length}] = {\n${rows.join('\n')}\n};\n`;
}
const want = { isl: Buffer.from(a), inc: Buffer.from(inc(a)), web: Buffer.from(text) };
let bad = 0;
for (const k of Object.keys(OUT)) {
  const p = path.join(root, OUT[k]);
  if (check) {
    if (!fs.existsSync(p) || !fs.readFileSync(p).equals(want[k])) { console.error(`island-pack: ${OUT[k]} is stale (make island-pack)`); bad = 1; }
  } else {
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, want[k]);
  }
}
if (bad) process.exit(1);
console.log(`${check ? 'checked' : 'wrote'} ${OUT.isl} (${a.length} bytes, crc ${crc32(a, 12, 16).toString(16).padStart(8, '0')}), ${OUT.inc}, ${OUT.web}`);
