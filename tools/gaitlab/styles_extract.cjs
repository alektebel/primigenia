#!/usr/bin/env node
// No dependencies beyond the repo's three.js r128. Regenerate the inline table:
// node tools/gaitlab/styles_extract.cjs --write (or --check for drift).
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '../..');
const THREE = require(path.join(root, 'web/biome/three.min.js'));
const files = ['starters/b_runner.json', 'hatchling.json', 'starters/a_grazer.json', 'starters/c_sprawler.json', 'starters/d_knuckle.json'];
const names = ['starter B', 'hatchling', 'starter A', 'starter C', 'starter D'];
function extract(file, index) {
  const source = 'godot/game/data/' + file;
  const g = JSON.parse(fs.readFileSync(path.join(root, source)));
  // Uniform Catmull-Rom tension .5, as Creature._sample_spine. Continuous
  // surface approximation (not Godot's capped 60-sample/frame quantisation).
  const curve = new THREE.CatmullRomCurve3(g.nodes.map(n => new THREE.Vector3(n.z, n.y, n.r)), false, 'catmullrom', .5);
  const legs = g.parts.filter(p => ['pata', 'zanca', 'pezuna'].includes(p.type)).sort((a,b) => a.t-b.t).map(p => {
    const v = curve.getPoint(p.t), tangent = curve.getTangent(p.t);
    const r = Math.max(.03, v.z), ca = Math.cos(p.ang), sa = Math.sin(p.ang);
    const up = new THREE.Vector2(-tangent.y, tangent.x).normalize();
    return {x:v.x+up.x*ca*.9*r, y:v.y+up.y*ca*.9*r, z:sa*r,
      a:Math.hypot(...p.k), b:Math.hypot(...p.f.map((v,i)=>v-p.k[i])), width:p.w, footZ:p.f[0], restK:p.k, restF:p.f};
  });
  return {name:names[index], source, color:g.skin.cA, accent:g.skin.cC, nodes:g.nodes.map(n=>[n.z,n.y,n.r]), legs,
    hipHeight:legs.reduce((s,l)=>s+l.y,0)/legs.length,
    bodyLength:g.nodes[5].z-g.nodes[2].z, neckLength:Math.hypot(g.nodes[7].y-g.nodes[5].y,g.nodes[7].z-g.nodes[5].z),
    headRadius:g.nodes[7].r, tailLength:g.nodes[2].z-g.nodes[0].z,
    mouth:g.parts.find(p=>['pico','romo'].includes(p.type))?.type||'romo',
    armour:g.parts.filter(p=>p.type==='placa').map(p=>p.t), arms:g.parts.some(p=>p.type.startsWith('arm_'))};
}
const table = files.map(extract);
// Generic controls: explicit starting values, not claimed genome measurements.
for (const biped of [false,true]) table.push({name:biped?'generic biped':'generic quadruped',source:'starting values: M1 move-style comparison',color:biped?'#75a6a0':'#b79b72',accent:'#e7d6b7',
  nodes:[[-.95,.7,.025],[-.72,.72,.045],[-.48,.74,.13],[-.2,.76,.18],[.18,.78,.19],[.42,.8,.13],[.58,1,.08],[.76,1.12,.12]],
  legs:(biped?[[-.12,.72]]:[[-.36,.72],[.36,.76]]).map(([x,y])=>({x,y,z:.14,a:.44,b:.43,width:.055,footZ:.06,restK:[.04,-.4,.12],restF:[.06,-.75,0]})),
  hipHeight:.74,bodyLength:.9,neckLength:.46,headRadius:.12,tailLength:.47,mouth:biped?'pico':'romo',armour:[],arms:false});
const json=JSON.stringify(table,(_,v)=>typeof v==='number'?Math.round(v*1e6)/1e6:v,2);
const page=path.join(root,'web/gaitlab/styles.html');
const block='/* GENOMES_BEGIN: generated by tools/gaitlab/styles_extract.cjs */\nconst BODIES = '+json+';\n/* GENOMES_END */';
if(process.argv.includes('--write')||process.argv.includes('--check')) {
  const html=fs.readFileSync(page,'utf8');
  const next=html.replace(/\/\* GENOMES_BEGIN[\s\S]*?\/\* GENOMES_END \*\//,block);
  if(next===html && !html.includes(block)) throw Error('Missing genome markers');
  if(process.argv.includes('--check')) {if(next!==html)throw Error('Inline genomes stale'); console.log('Inline genomes match all five source files + two generic controls');}
  else fs.writeFileSync(page,next);
} else console.log(block);
