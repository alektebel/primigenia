"""Run a seeds x personas matrix (resumable) and write docs/audit/AGENTPLAY.md.
   batch.py --policy llm --seeds 5 --turns 80
   batch.py --policy scripted --seeds 5 --turns 200
   batch.py --report-only"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
RUNS = os.path.join(HERE, "runs")
sys.path.insert(0, HERE)
from policies import PERSONAS  # noqa: E402
from repro import shrink  # noqa: E402

THEMES = [
    ("No victory/defeat/outcome feedback", ["win", "won", "victory", "defeat", "outcome", "goal", "objective", "end condition", "game over", "died", "death"]),
    ("Enemy state invisible (hp, attack, intent, fight in progress)", ["enemy hp", "opponent", "garfio", "health of", "its hp", "target's", "creature's hp", "hp of", "combat state", "in combat", "damage", "cooldown", "attack range", "hit"]),
    ("Units / coordinates / bearing / world size unclear", ["unit", "coordinate", "bearing", "world size", "bounds", "boundar", "map", "scale", "direction", "north", "heading", "angle", "degree"]),
    ("Errors / rejected command feedback unclear", ["error", "invalid", "reject", "fail", "last_error", "feedback"]),
    ("Attack moves unexplained (effects, cost, range)", ["move", "bite", "charge", "spit", "tail", "stamina cost", "stamina"]),
    ("Order semantics (persistence, flee/go_nest/wait meaning)", ["flee", "go_nest", "nest", "persist", "keep running", "standing order", "wait", "order"]),
    ("Healing / regeneration / nest function unclear", ["heal", "regen", "recover", "restore", "nest"]),
    ("Nearby list limits (range, hidden entities, ids)", ["nearby", "range", "see", "vision", "visible", "hidden", "id", "entit", "carcass", "rock", "tree", "terrain"]),
]


def theme_of(line):
    l = line.lower()
    for name, kws in THEMES:
        if any(k in l for k in kws):
            return name
    return "Other"


def run_matrix(args):
    jobs = []
    for seed in range(1, args.seeds + 1):
        for persona in args.personas:
            tag = args.policy if args.policy != "llm" else args.model
            rid = f"{tag}-{persona}-s{seed}-t{args.turns}"
            if os.path.exists(os.path.join(RUNS, rid, "summary.json")):
                continue
            jobs.append((seed, persona, rid))
    print(f"{len(jobs)} episodes to run", flush=True)

    def go(j):
        seed, persona, rid = j
        cmd = ["nice", "-n", "10", sys.executable, os.path.join(HERE, "play.py"), "--seed", str(seed),
               "--persona", persona, "--turns", str(args.turns), "--policy", args.policy,
               "--model", args.model, "--ticks-per-turn", str(args.ticks_per_turn)]
        t = time.time()
        r = subprocess.run(cmd, capture_output=True, text=True)
        ok = os.path.exists(os.path.join(RUNS, rid, "summary.json"))
        print(f"{'ok ' if ok else 'FAIL'} {rid} {time.time() - t:.0f}s {r.stderr[-200:] if not ok else ''}", flush=True)
        if not ok:  # crash is itself a finding: record it
            os.makedirs(os.path.join(RUNS, rid), exist_ok=True)
            json.dump({"id": rid, "seed": seed, "persona": persona, "policy": args.policy,
                       "model": args.model if args.policy == "llm" else None, "turns": args.turns,
                       "crash": r.stderr[-800:], "bugs": [{"kind": "harness_crash", "detail": r.stderr[-200:], "seed": seed, "repro": []}],
                       "determinism": {"ok": None}, "error_by_verb": {}, "notes": []},
                      open(os.path.join(RUNS, rid, "summary.json"), "w"))

    with ThreadPoolExecutor(args.workers) as ex:
        list(ex.map(go, jobs))


def load(policy_key):
    out = []
    for p in sorted(glob.glob(os.path.join(RUNS, "*", "summary.json"))):
        s = json.load(open(p))
        key = s.get("model") or s.get("policy")
        if policy_key == "all" or key == policy_key:
            out.append(s)
    return out


def pct(n, d):
    return f"{100 * n / d:.0f}%" if d else "-"


def report(groups, args):
    L = ["# AGENTPLAY: LLM playtest harness audit", "",
         f"Generated by `tools/agentplay/batch.py` on {time.strftime('%Y-%m-%d')}. Interface under test: `bindings/python/cpore/world.py` "
         "(StageWorld, schema world-1, creature stage C sim). One agent turn = one command + N sim ticks (default 20 = 2 s); "
         "invariants are checked on every tick.", ""]
    L += HOWTO.split("\n")
    tot_p = tot_c = 0
    allsum = [s for g in groups.values() for s in g]
    for key, S in groups.items():
        L += ["", f"## Results: `{key}` ({len(S)} episodes)", "",
              "| persona | eps | turns | win | any death | avg deaths | stuck | nondeterm. | invalid replies | cmd error rate | max repeat | cells | tokens (prompt+compl.) |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for persona in PERSONAS:
            P = [s for s in S if s["persona"] == persona and "crash" not in s]
            if not P:
                continue
            n = len(P)
            issued = sum(s.get("commands_issued", 0) for s in P)
            errs = sum(s.get("command_errors", 0) for s in P)
            tp = sum(s.get("tokens", {}).get("prompt", 0) for s in P)
            tc = sum(s.get("tokens", {}).get("completion", 0) for s in P)
            tot_p += tp
            tot_c += tc
            L.append(f"| {persona} | {n} | {P[0]['turns']} | {pct(sum(s['won'] for s in P), n)} | {pct(sum(s['deaths'] > 0 for s in P), n)} | "
                     f"{sum(s['deaths'] for s in P) / n:.1f} | {pct(sum(s['stuck'] for s in P), n)} | "
                     f"{pct(sum(s['determinism'].get('ok') is False for s in P), n)} | "
                     f"{pct(sum(s.get('invalid_replies', 0) for s in P), sum(s['turns'] for s in P))} | {pct(errs, issued)} | "
                     f"{max(s.get('longest_repeat', 0) for s in P)} | {sum(s.get('cells_visited', 0) for s in P) / n:.0f} | {tp + tc} |")
        crashes = [s for s in S if "crash" in s]
        if crashes:
            L.append(f"\n{len(crashes)} episodes crashed the harness (listed under bugs).")
        # per-verb error rate
        verbs = collections.defaultdict(lambda: [0, 0])
        for s in S:
            for v, d in s.get("error_by_verb", {}).items():
                verbs[v][0] += d["n"]
                verbs[v][1] += d["err"]
        if verbs:
            L += ["", "Command error rate per verb (rejected / issued): " +
                  ", ".join(f"`{v}` {e}/{n}" for v, (n, e) in sorted(verbs.items(), key=lambda kv: -kv[1][0]))]

    # bugs
    L += ["", "## Bugs (deduplicated)", ""]
    INFO = {"silent_noop", "last_error_blind"}
    bugs = collections.OrderedDict()
    for s in allsum:
        for b in s.get("bugs", []):
            key = (b["kind"], b["detail"][:40] if b["kind"] not in ("stuck", "no_effect") else b["detail"].split("'")[1] + ("/edge" if "edge" in b["detail"] else "") if "'" in b["detail"] else "")
            e = bugs.setdefault(key, {"b": b, "n": 0, "eps": []})
            e["n"] += 1
            e["eps"].append(s["id"])
            if len(b.get("repro", [])) < len(e["b"].get("repro", [])) or (not e["b"].get("repro") and b.get("repro")):
                e["b"] = b
    real = [(k, v) for k, v in bugs.items() if k[0] not in INFO]
    info = [(k, v) for k, v in bugs.items() if k[0] in INFO]
    if not real:
        L.append("No invariant violations were found in these runs.")
    for (kind, _), e in sorted(real, key=lambda kv: -kv[1]["n"]):
        b = e["b"]
        L += [f"### `{kind}`: {b['detail']}", f"- Episodes affected: {e['n']} (e.g. `{e['eps'][0]}`)"]
        if b.get("repro") is not None and kind not in ("harness_crash",) and not args.no_shrink:
            r = shrink(b["seed"], b.get("ticks_per_turn", 20), b["turn"], b["repro"], kind, b["detail"][:40], budget=150)
            if r:
                ops = ", ".join(f"turn {t}: `{c}`" for t, c in r["ops"]) or "(no commands, initial state)"
                L.append(f"- Minimal repro (verified): seed {r['seed']}, {r['ticks_per_turn']} ticks/turn, run {r['turns']} turns; commands: {ops}")
                L.append(f"  `python3 tools/agentplay/repro.py --seed {r['seed']} --tpt {r['ticks_per_turn']} --turns {r['turns']} --kind {kind} --ops '{json.dumps(r['ops'])}'`")
            else:
                L.append(f"- Repro (unshrunk, did not re-trigger from prefix): seed {b['seed']}, ops {json.dumps(b['repro'])[:300]}")
        L.append("")
    if info:
        L += ["### Interface findings flagged automatically (not crashes)", ""]
        for (kind, _), e in sorted(info, key=lambda kv: -kv[1]["n"]):
            L.append(f"- `{kind}` x{e['n']} episodes: {e['b']['detail']}")

    # usability
    L += ["", "## Usability issues (ranked by frequency)", "",
          "Source: end-of-episode question to the model plus per-turn NOTE lines (themes grouped by keywords, one count per episode). "
          "Counts are number of episodes whose model mentioned the theme.", ""]
    llm = [s for s in allsum if s.get("usability_llm")]
    themes = collections.defaultdict(lambda: {"eps": set(), "ex": []})
    for s in llm:
        for line in s["usability_llm"]:
            t = theme_of(line)
            themes[t]["eps"].add(s["id"])
            if len(themes[t]["ex"]) < 2:
                themes[t]["ex"].append(f"{line[:230]} ({s['persona']})")
    if themes:
        L += ["| # | theme | episodes |", "|---|---|---|"]
        for i, (t, d) in enumerate(sorted(themes.items(), key=lambda kv: -len(kv[1]["eps"])), 1):
            L.append(f"| {i} | {t} | {len(d['eps'])}/{len(llm)} |")
        L.append("")
        for t, d in sorted(themes.items(), key=lambda kv: -len(kv[1]["eps"])):
            L.append(f"- **{t}**: " + " / ".join(f'"{x}"' for x in d["ex"]))
    else:
        L.append("No LLM episodes yet.")
    L += ["", "Automatic metrics (all episodes with this policy): see the per-persona tables above "
          "(invalid reply rate, error rate, longest repeated identical command)."]
    L += AUTO_NOTES
    if tot_p + tot_c:
        L += ["", "## Tokens", "", f"LLM tokens in the reported batches: {tot_p} prompt + {tot_c} completion = {tot_p + tot_c} "
              f"over {sum(s.get('tokens', {}).get('calls', 0) for s in allsum)} calls (prompt kept to system + notes + last 20 turns + current JSON observation)."]
    L += LIMITS
    return "\n".join(L) + "\n"


HOWTO = """## How to run

```
make lib build/world_cli                       # once; build/libcpore.so must exist
# one episode (LLM; needs $NAN_API_KEY, model qwen3.6 on api.nan.builders, max 4 concurrent calls)
python3 tools/agentplay/play.py --seed 3 --persona fighter --turns 80 --model qwen3.6
# one episode without an LLM
python3 tools/agentplay/play.py --policy scripted --persona explorer --seed 3 --turns 200
python3 tools/agentplay/play.py --policy random   --persona chaos    --seed 3 --turns 200
# matrix (seeds 1..N x all personas), resumable: finished runs/<id>/summary.json are skipped
python3 tools/agentplay/batch.py --policy llm --seeds 5 --turns 80
python3 tools/agentplay/batch.py --policy scripted --seeds 5 --turns 200
python3 tools/agentplay/batch.py --report-only   # rebuild this file from tools/agentplay/runs/
# shrink / re-check a bug repro
python3 tools/agentplay/repro.py --seed S --tpt 20 --turns T --kind stuck --ops '[[0,"heading 90"]]'
```

Each run writes `tools/agentplay/runs/<id>/log.jsonl` (per turn: observation, prompt chars, raw reply, parse mode, action, error) and `summary.json`.
Personas: fighter, explorer, survivor, chaos, newcomer (must explain what it does not understand).

Invariants checked every tick: NaN/inf, hp/stamina in [0,max], position within the walkable +-195, teleports (>3 units/tick without a respawn at the nest), tick monotonic,
schema drift (exact key lists, known verbs/types/errors), dead creature moving, binding exceptions. Every turn: movement verb accepted but no motion / stuck for 3 turns (outside combat range),
advertised `legal_verbs` probed on a clone of the world (must be accepted; unadvertised target verbs must not be), `last_error` visibility.
At episode end the full command log is replayed on a fresh world and all per-tick hashes are compared (determinism)."""

AUTO_NOTES = ["", "Observations on the interface itself (from reading the observation and the transcripts):",
              "- The observation has no outcome field: victory (creature turns into `carcass`) and death (hp 0, respawn at nest after 20 ticks) are only inferable.",
              "- No information on the opponent's hp, whether a fight is in progress, attack cooldowns or stamina costs.",
              "- `last_error` in `observe()` reflects only the struct (dict) input path: with the text-command API a rejected command is reported by the return code of `command()` only, and the next `step()` resets it to ok."]
LIMITS = ["", "## Limits of this harness", "",
          "- Creature stage only, one wild creature type fight at a time; walkable bounds (+-195) are inferred from `cp_stage_can_walk`, not exported.",
          "- Stuck/no-effect checks are heuristic and skipped near creatures (< 7 units) because combat roots the player.",
          "- Usability themes are keyword buckets over free text from a small model, so counts are indicative only.",
          "- Extension to the Godot game: see the end of this file."]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--policy", default="llm", choices=["llm", "scripted", "random"])
    ap.add_argument("--model", default="qwen3.6")
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--personas", nargs="*", default=list(PERSONAS))
    ap.add_argument("--turns", type=int, default=80)
    ap.add_argument("--ticks-per-turn", type=int, default=20)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--no-shrink", action="store_true")
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "audit", "AGENTPLAY.md"))
    a = ap.parse_args()
    a.workers = min(a.workers, 4)
    if not a.report_only:
        run_matrix(a)
    groups = collections.OrderedDict()
    for key in ["scripted", "random", a.model]:
        S = load(key)
        if S:
            groups[key] = S
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    body = report(groups, a)
    ext = os.path.join(HERE, "AGENTPLAY_EXTRA.md")
    if os.path.exists(ext):
        body += "\n" + open(ext).read()
    open(a.out, "w").write(body)
    print("wrote", a.out)


if __name__ == "__main__":
    main()
