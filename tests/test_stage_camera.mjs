import assert from 'node:assert/strict';
import {ChaseCamera} from '../web/stage/camera.js';
import {FightFeedback,moveTell} from '../web/stage/feedback.js';
const flat=()=>0,p={x:0,z:0,yaw:0,speed:0};
const camera=new ChaseCamera({height:3,yaw:Math.PI});
let shot=camera.update({player:p,groundY:flat,dt:0,aspect:1.6});
assert(shot.pitch>=12*Math.PI/180&&shot.pitch<=18*Math.PI/180);
assert.equal(shot.target.y,4.5);assert.equal(shot.distance,18);
const horizon=.5-Math.tan(shot.pitch)/(2*Math.tan(24*Math.PI/180));
assert(horizon>0&&horizon<=1/3);
camera.orbit(100,0);const offset=Math.abs(camera.yaw-Math.PI);
for(let i=0;i<60;i++)camera.update({player:{...p,speed:2},groundY:flat,dt:1/60,aspect:1.6});
assert(Math.abs(camera.yaw-Math.PI)<offset*.15,'follow time constant .4 seconds');
camera.zoom(1e4);shot=camera.update({player:p,groundY:flat,dt:0,aspect:1.6});assert(shot.pitch>.6);assert.equal(shot.distance,36);
camera.zoom(-1e4);shot=camera.update({player:p,groundY:flat,dt:0,aspect:1.6});assert(Math.abs(shot.distance-8.4)<1e-9);
const ridge=(x,z)=>z<-5?20:0;
shot=camera.update({player:p,groundY:ridge,dt:0,aspect:1.6});assert(shot.position.y>=ridge(shot.position.x,shot.position.z)+.65);assert(shot.actualDistance<shot.distance);
const fight=new ChaseCamera({height:3,yaw:Math.PI});
shot=fight.update({player:p,enemy:{...p,x:16},fighting:true,groundY:flat,dt:0,aspect:1.6});
assert.equal(shot.target.x,8);assert(shot.distance>18);
shot=fight.update({player:p,groundY:flat,dt:2,aspect:1.6});assert(shot.target.x<.01);assert(Math.abs(shot.distance-18)<.1);
for(const move of [0,1,2,3,4,5])assert(moveTell(move).name&&moveTell(move).color);
assert.equal(new Set([0,1,3,4].map(m=>moveTell(m).color)).size,4);
const feedback=new FightFeedback();feedback.tick({events:[{type:1,b:1}],ticks:1});
assert(feedback.frozen);assert(feedback.flash(1).strength>0);assert(feedback.shake>0);
feedback.update(1/60);assert(feedback.frozen);feedback.update(1/60);assert(feedback.frozen);feedback.update(1/60);assert(!feedback.frozen);
feedback.tick({events:[{type:2,b:0},{type:4,b:1}],ticks:2});assert.equal(feedback.flash(0).kind,'guard');assert.equal(feedback.flash(1).kind,'dodge');
feedback.tick({events:[{type:2,b:0},{type:1,b:0}],ticks:3});assert.equal(feedback.flash(0).kind,'guard','partial blocks retain the success flash');
feedback.update(1);assert.equal(feedback.flash(0).strength,0);assert.equal(feedback.shake,0);
console.log('PASS chase composition, scale, follow, zoom, terrain, fight return, move tells and impact feedback');
